import { followersCount, followersLabel } from './followers';

describe('followers', () => {
  it.each([
    [349, '349'], [1000, '1 000'], [1234, '1 234'], [9999, '9 999'],
    [10000, '10 тыс.'], [12345, '12,3 тыс.'], [48200, '48,2 тыс.'], [999949, '999,9 тыс.'],
    [1000000, '1 млн'], [1234567, '1,2 млн'], [12500000, '12,5 млн'],
  ])('число %i → «%s»', (n, out) => {
    expect(followersCount(n)).toBe(out);
  });

  it.each([
    [1, 'подписчик'], [2, 'подписчика'], [5, 'подписчиков'], [11, 'подписчиков'], [21, 'подписчик'],
    [349, 'подписчиков'], [1234, 'подписчика'], [12345, 'подписчиков'], [1234567, 'подписчиков'],
  ])('слово для %i → «%s»', (n, word) => {
    expect(followersLabel(n)).toBe(word);
  });
});
