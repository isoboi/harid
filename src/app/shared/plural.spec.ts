import { plural } from './plural';

const F: [string, string, string] = ['лавка', 'лавки', 'лавок'];

describe('plural', () => {
  it.each([
    [0, 'лавок'], [1, 'лавка'], [2, 'лавки'], [4, 'лавки'], [5, 'лавок'],
    [11, 'лавок'], [12, 'лавок'], [14, 'лавок'], [21, 'лавка'], [22, 'лавки'], [25, 'лавок'], [111, 'лавок'], [101, 'лавка'],
  ])('%i → %s', (n, word) => expect(plural(n, F)).toBe(word));
});
